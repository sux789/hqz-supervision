def headers_from(path):
    wb = openpyxl.load_workbook(path, read_only=True, data_only=True)
    try:
        if 'data' not in wb.sheetnames:
            return []
        rows = wb['data'].iter_rows(max_row=1, values_only=True)
        return [str(x) for x in next(rows) if x not in (None, '')]
    finally:
        try:
            wb.close()
        except Exception:
            pass


def main():
    ap = argparse.ArgumentParser(description='生成《流程配置-业务专家填写版.xlsx》')
    ap.add_argument('--out', default=str(DEFAULT_OUT))
    ap.add_argument('--headers-from', default=str(DEFAULT_TPL))
    a = ap.parse_args()
    heads = headers_from(a.headers_from) if Path(a.headers_from).exists() else []
    out = build(heads, a.out)
    print(f'已生成 {out}')
    print(f'  data 列名 {len(heads)} 个 → ⑤字段字典')
    print(f'  ①流程 {len(FLOWS)} 条 / ②环节 {len(STEPS)} 个 / ③核验项 {len(FIELDS)} 项')
    res = fc.parse_path(out, data_headers=heads)
    s = res['summary']
    print(f'  自检：错误 {len(res["errors"])} 条，提示 {len(res["warnings"])} 条'
          f' → 流程 {s.get("flows")} 条 / 环节 {s.get("steps")} 个 / 入口 {s.get("entries")}')
    if res['errors']:
        print(fc.check_lines(res))
        return 1
    if res['warnings']:
        print(fc.check_lines({'errors': [], 'warnings': res['warnings']}, limit=10))
    return 0


if __name__ == '__main__':
    sys.exit(main())
