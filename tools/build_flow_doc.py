def _col(cols, name):
    return get_column_letter(cols.index(name) + 1)


def _hdr(ws, cols, widths, notes=None):
    for i, c in enumerate(cols, 1):
        cell = ws.cell(row=1, column=i, value=c)
        cell.font = Font(bold=True, color='FFFFFFFF', size=11)
        cell.fill = PatternFill('solid', fgColor=GREEN)
        cell.alignment = Alignment(horizontal='center', vertical='center', wrap_text=True)
        cell.border = BORDER
        ws.column_dimensions[get_column_letter(i)].width = widths[i - 1]
        if notes and c in notes:
            cell.comment = Comment(notes[c], '系统')
    ws.row_dimensions[1].height = 36
    ws.freeze_panes = 'C2'
    ws.auto_filter.ref = f'A1:{get_column_letter(len(cols))}1'


def _body(ws, rows):
    for r, row in enumerate(rows, 2):
        for c, v in enumerate(row, 1):
            cell = ws.cell(row=r, column=c, value=v)
            cell.alignment = Alignment(vertical='top', wrap_text=True)
            cell.border = BORDER
            if r % 2 == 0:
                cell.fill = PatternFill('solid', fgColor=GREY_L)


def _dv(ws, formula, col_letter, n, strict=True, hint=''):
    dv = DataValidation(type='list', formula1=formula, allow_blank=True,
                        showErrorMessage=strict, showDropDown=False)
    dv.errorTitle = '取值不合法'
    dv.error = hint or '请从下拉里选'
    dv.promptTitle = '可选项'
    dv.prompt = hint
    ws.add_data_validation(dv)
    dv.add(f'{col_letter}2:{col_letter}{n}')


def _loose_list(ws, formula, col_letter, n, hint=''):
    dv = DataValidation(type='list', formula1=formula, allow_blank=True,
                        showErrorMessage=False, showDropDown=False)
    dv.promptTitle = '候选'
    dv.prompt = hint
    ws.add_data_validation(dv)
    dv.add(f'{col_letter}2:{col_letter}{n}')


